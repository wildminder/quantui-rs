//! Tier 2 S06 — reconstruction-error benchmark for the opt-in quality modes.
//!
//! MEASURES, DOES NOT GATE. The point of this bench is to make "is the quality
//! mode actually better?" a *measured, reproducible* question instead of an
//! assertion. It PRINTS a base-vs-quality table; it is not a pass/fail gate.
//! Benches do not run in `cargo test`, and turning a criterion bench into a
//! hard gate would be the wrong tool for a decision that needs review.
//!
//! # The metric
//!
//! ```text
//! rel_l2 = Σ (w − dequantize(quantize(w)))²  /  Σ w²
//! ```
//!
//! accumulated in **f64**, with the reconstruction produced by the SHIPPED
//! PUBLIC dequantizers -- [`dequantize_nvfp4`] and [`dequantize_mxfp8`].
//! There is deliberately no private reimplementation of the dequant math here:
//! a private copy could drift from the shipped one, and then this bench would
//! be measuring something the crate does not actually do at runtime. The
//! `w` in the numerator and denominator is the ORIGINAL fixture tensor, not
//! the bf16-rounded or zero-padded internal copy.
//!
//! # The pre-registered decision rule
//!
//! Fixed BEFORE any of these numbers were measured, reproduced verbatim in the
//! printed output so the verdict is mechanical rather than retrofitted:
//!
//! | Outcome                                          | Action                        |
//! |--------------------------------------------------|-------------------------------|
//! | improves rel_l2 on >=3 of 4 AND none regress >1% | SHIP                          |
//! | improves on <3 of 4                              | DO NOT SHIP                   |
//! | any distribution regresses by >1%                 | DO NOT SHIP                   |
//! | gain <2% aggregate                               | MARGINAL — keep, do not advertise |
//!
//! "improves" = ratio < 1.0. "regresses by >1%" = ratio > 1.01. "aggregate" =
//! the mean of the four per-distribution relative gains, `(1 − mean(ratio))`,
//! stated in the output so the arithmetic is not a black box.
//!
//! The unit of counting is the DISTRIBUTION, not the row. The fixture carries
//! four shapes per distribution, so counting rows would silently turn the "3
//! of 4" bar into "12 of 16" and make the rule four times easier to clear.
//! `per_distribution` collapses each format's rows to one mean ratio per
//! distribution before any of the rule is applied.
//!
//! # `int8_clip09` — the S07 arm, and why it is here
//!
//! The third row of the table is INT8 absmax clipping
//! ([`quantize_int8_weight_clipped`], `--format int8_clip09`): the quant scale
//! comes from `0.9 * row_max` rather than `row_max`, trading the top of the
//! range for finer steps below it.
//!
//! It is measured in **row** scaling, which is the mode the clip is defined in
//! terms of and the only one that covers the whole fixture (the block path
//! asserts divisibility, and two of the four shapes are prime in one or both
//! dimensions).
//!
//! The ratio is FIXED at [`INT8_CLIP_RATIO`] and is not a parameter here. A
//! sweep over clip ratios, evaluated until one of them cleared the bar, would
//! be a threshold fitted to this fixture rather than a measurement of the idea
//! — and this bench's whole purpose is to be the thing that cannot be tuned
//! into a pass.
//!
//! # MEASURED RESULT: DO NOT SHIP
//!
//! Recorded here so the verdict travels with the code that produced it:
//!
//! ```text
//! int8_clip09  aggregate gain -2.5e13%   worst regression 9.9e13%   improved 0/4
//! ```
//!
//! 0 of 4 distributions improved and every one regressed, so the rule fires
//! twice over (`<3 of 4` and `>1%` regression). This is not a marginal miss —
//! the mode is 31x-14000x worse than plain INT8. The mechanism is structural:
//! INT8's 127 levels leave almost no rounding error for a finer step to
//! recover, while the saturated tail's error is unbounded by the step. See
//! `tests/int8_clip09_negative_result.rs` for the full analysis, including an
//! independent analytic model that confirms the kernel is correct and the
//! regression is real.
//!
//! # Fixture
//!
//! `tests/fixtures/quality/{weights.f32,manifest.json}`, generated by
//! `tools/gen_quality_bench.py` and COMMITTED. Both `include_bytes!` paths
//! below point into `crates/`, never into `docs/` — `.gitignore:16` ignores
//! `docs/` wholesale, and a build input pointing at an ignored file breaks the
//! whole bench binary on a fresh clone. The manifest's SHA-256 is verified
//! against the blob at startup, so a silently-swapped or truncated fixture
//! fails loudly instead of reporting plausible-looking numbers.
//!
//! # A note on what is (and is not) timed
//!
//! The NVFP4 quality path is a search and is far more expensive than the
//! default path. Timing it inside the criterion loop would take minutes per
//! distribution and would measure search COST, which is not what this bench is
//! for. So the table is computed ONCE, up front and untimed, from the shipped
//! entry points; the timed portion below is the cheap dequantize + rel_l2
//! measurement, which is what actually recurs in a real pipeline. The printed
//! table is the deliverable; the criterion HTML report is a bonus.

use std::sync::OnceLock;

use criterion::{criterion_group, criterion_main, BenchmarkId, Criterion, Throughput};
use quant_core::quant::{
    dequantize_int8, quantize_int8_weight, quantize_int8_weight_clipped, Int8QuantResult,
    ScalingMode as Int8ScalingMode, INT8_CLIP_RATIO,
};
use quant_core::quant_mxfp8::{
    dequantize_mxfp8, quantize_mxfp8_weight, quantize_mxfp8_weight_compensated, Mxfp8QuantResult,
};
use quant_core::quant_nvfp4::{
    dequantize_nvfp4, quantize_nvfp4_weight, quantize_nvfp4_weight_quality, Nvfp4QuantResult,
};

const BLOB: &[u8] = include_bytes!("../tests/fixtures/quality/weights.f32");
const MANIFEST: &str = include_str!("../tests/fixtures/quality/manifest.json");

/// Regressions beyond this are disqualifying under the pre-registered rule.
const REGRESSION_TOLERANCE: f64 = 1.01;
/// Below this aggregate gain the mode is MARGINAL even if it technically wins.
const MARGINAL_GAIN: f64 = 0.02;
/// A distribution must land under this ratio to count as "improved".
const IMPROVED_RATIO: f64 = 1.0;

// ---------------------------------------------------------------------------
// Fixture loading
// ---------------------------------------------------------------------------

/// One (distribution, shape) fixture case, materialized as f32.
struct Case {
    id: String,
    distribution: String,
    rows: usize,
    cols: usize,
    w: Vec<f32>,
}

impl Case {
    fn len(&self) -> usize {
        self.w.len()
    }
}

/// Minimal view of one manifest entry. Hand-parsed through `serde_json::Value`
/// rather than a `#[derive(Deserialize)]` struct: the manifest is a fixture
/// that a Python generator owns, and a struct here would be a second place for
/// its shape to drift.
fn load_cases() -> Vec<Case> {
    let v: serde_json::Value =
        serde_json::from_str(MANIFEST).expect("quality fixture manifest must be valid JSON");
    let cases = v["cases"]
        .as_array()
        .expect("manifest must carry a `cases` array");

    let mut out = Vec::with_capacity(cases.len());
    for c in cases {
        let offset = c["offset_elements"]
            .as_u64()
            .expect("offset_elements must be an integer") as usize;
        let length = c["length_elements"]
            .as_u64()
            .expect("length_elements must be an integer") as usize;

        let start = offset * 4;
        let end = start + length * 4;
        let bytes = BLOB.get(start..end).unwrap_or_else(|| {
            panic!(
                "fixture case {id} runs past the end of the blob",
                id = c["id"]
            )
        });

        let w: Vec<f32> = bytes
            .chunks_exact(4)
            .map(|c| f32::from_le_bytes([c[0], c[1], c[2], c[3]]))
            .collect();
        debug_assert_eq!(w.len(), length);

        out.push(Case {
            id: c["id"]
                .as_str()
                .expect("case id must be a string")
                .to_string(),
            distribution: c["distribution"]
                .as_str()
                .expect("distribution must be a string")
                .to_string(),
            rows: c["rows"].as_u64().expect("rows must be an integer") as usize,
            cols: c["cols"].as_u64().expect("cols must be an integer") as usize,
            w,
        });
    }
    out
}

/// Verify the blob against the SHA-256 the generator recorded.
///
/// Cheap insurance against the failure mode this whole fixture layout exists to
/// prevent: a bench that silently measures the wrong bytes and reports
/// confident nonsense. Uses the `sha2` dependency the crate already ships for
/// its parity fingerprint.
fn verify_blob_digest() {
    use sha2::{Digest, Sha256};

    let v: serde_json::Value =
        serde_json::from_str(MANIFEST).expect("quality fixture manifest must be valid JSON");
    let want = v["blob_sha256"]
        .as_str()
        .expect("manifest must carry a blob_sha256");
    let got = format!("{:x}", Sha256::digest(BLOB));
    assert_eq!(
        got, want,
        "quality fixture blob does not match the manifest SHA-256; \
         regenerate with `python tools/gen_quality_bench.py` (it is deterministic)"
    );
}

// ---------------------------------------------------------------------------
// The metric
// ---------------------------------------------------------------------------

/// `Σ (w − recon)² / Σ w²`, accumulated in f64.
///
/// The dequantizers return exactly `m * n` values already cropped back to the
/// unpadded shape, so `w` and `recon` are directly index-aligned — no stride
/// arithmetic and no masked tail here. That cropping is the shipped behaviour,
/// not an assumption of this bench.
fn rel_l2(w: &[f32], recon: &[f32]) -> f64 {
    assert_eq!(
        w.len(),
        recon.len(),
        "reconstruction must match the original tensor element-for-element"
    );
    let mut num = 0.0f64;
    let mut den = 0.0f64;
    for (&orig, &rec) in w.iter().zip(recon.iter()) {
        let o = f64::from(orig);
        let d = o - f64::from(rec);
        num += d * d;
        den += o * o;
    }
    num / den
}

