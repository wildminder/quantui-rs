/// Which format a row belongs to, and how to produce its base/quality pair.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Format {
    Nvfp4,
    Mxfp8,
    Int8Clip,
}

impl Format {
    fn name(self) -> &'static str {
        match self {
            Format::Nvfp4 => "nvfp4",
            Format::Mxfp8 => "mxfp8",
            Format::Int8Clip => "int8_clip09",
        }
    }

    /// `base` and `quality` reconstruction error for one tensor.
    ///
    /// Both arms go quantize -> SHIPPED dequantize. `quality` for MXFP8 is the
    /// proven no-op (measured at exactly 0.00% improvement, not shipped); it
    /// stays wired up so the negative result stays reproducible on demand —
    /// a benchmark that only ever runs the winner is not a benchmark.
    ///
    /// # Why INT8 is measured in ROW mode
    ///
    /// `int8_clip09` clips the per-row absmax, which is what
    /// `quantize_int8_weight_clipped` does in every scaling mode. ROW is the
    /// mode the clip is *defined* in terms of, and it is also the only mode
    /// that covers the whole fixture: the block path asserts divisibility by
    /// `block_size`, and `ragged_37x53` / `ragged_17x129` are prime in one or
    /// both dimensions, so a block-mode arm would panic on half the cases
    /// rather than measure them. The CLI preset is reachable in all three
    /// modes, but a partial-coverage INT8 row would be worse than an honest
    /// row-mode one.
    fn measure(self, w: &[f32], rows: usize, cols: usize) -> (f64, f64) {
        match self {
            Format::Nvfp4 => {
                let base = quantize_nvfp4_weight(w, rows, cols);
                let quality = quantize_nvfp4_weight_quality(w, rows, cols);
                (
                    rel_l2(w, &dequantize_nvfp4(&base, rows, cols)),
                    rel_l2(w, &dequantize_nvfp4(&quality, rows, cols)),
                )
            }
            Format::Mxfp8 => {
                let base = quantize_mxfp8_weight(w, rows, cols);
                let quality = quantize_mxfp8_weight_compensated(w, rows, cols);
                (
                    rel_l2(w, &dequantize_mxfp8(&base, rows, cols)),
                    rel_l2(w, &dequantize_mxfp8(&quality, rows, cols)),
                )
            }
            Format::Int8Clip => {
                // `block_size` is unused in Row mode; 128 keeps the value
                // canonical and matches the CLI default.
                let base = quantize_int8_weight(w, rows, cols, Int8ScalingMode::Row, 128);
                let quality = quantize_int8_weight_clipped(
                    w,
                    rows,
                    cols,
                    Int8ScalingMode::Row,
                    128,
                    INT8_CLIP_RATIO,
                );
                (
                    rel_l2(
                        w,
                        &dequantize_int8(
                            &base.qdata,
                            &base.scale,
                            rows,
                            cols,
                            Int8ScalingMode::Row,
                            128,
                        ),
                    ),
                    rel_l2(
                        w,
                        &dequantize_int8(
                            &quality.qdata,
                            &quality.scale,
                            rows,
                            cols,
                            Int8ScalingMode::Row,
                            128,
                        ),
                    ),
                )
            }
        }
    }
}

/// Every format the table reports on, in print order.
const FORMATS: [Format; 3] = [Format::Nvfp4, Format::Mxfp8, Format::Int8Clip];

struct Row {
    format: Format,
    distribution: String,
    shape: String,
    dims: String,
    base: f64,
    quality: f64,
    ratio: f64,
}

fn build_rows(cases: &[Case]) -> Vec<Row> {
    let mut rows = Vec::new();
    for format in FORMATS {
        for c in cases {
            let (base, quality) = format.measure(&c.w, c.rows, c.cols);
            rows.push(Row {
                format,
                distribution: c.distribution.clone(),
                shape: c.id.split('/').nth(1).unwrap_or("?").to_string(),
                dims: format!("{}x{}", c.rows, c.cols),
                base,
                quality,
                // A zero base error would make the ratio undefined; treat it as
                // "no measurable change" rather than NaN-poisoning the table.
                ratio: if base > 0.0 { quality / base } else { 1.0 },
            });
        }
    }
    rows
}

/// The pre-registered verdict for one format, evaluated mechanically.
struct Verdict {
    action: &'static str,
    improves: usize,
    total: usize,
    worst_regression: f64,
    aggregate_gain: f64,
    reasoning: String,
}

/// Collapse a format's rows to ONE ratio per distribution, in first-seen order.
///
/// The decision rule counts *distributions* ("improves on >=3 of 4"), and the
/// fixture carries four shapes per distribution. Counting shapes instead would
/// silently change the denominator from 4 to 16 and make the "3" bar four
/// times easier to clear — so the aggregation is done explicitly here rather
/// than left to whichever loop happens to run first. A distribution's ratio is
/// the mean of its shapes' ratios, which keeps the "aggregate gain" figure in
/// the printed table equal to the mean of the per-distribution gains.
fn per_distribution(rows: &[Row], format: Format) -> Vec<(String, f64)> {
    let mut order: Vec<String> = Vec::new();
    let mut sums: Vec<f64> = Vec::new();
    let mut counts: Vec<usize> = Vec::new();
    for r in rows.iter().filter(|r| r.format == format) {
        match order.iter().position(|d| *d == r.distribution) {
            Some(i) => {
                sums[i] += r.ratio;
                counts[i] += 1;
            }
            None => {
                order.push(r.distribution.clone());
                sums.push(r.ratio);
                counts.push(1);
            }
        }
    }
    order
        .into_iter()
        .zip(sums)
        .zip(counts)
        .map(|((d, s), c)| (d, s / c as f64))
        .collect()
}

fn evaluate(rows: &[Row], format: Format) -> Verdict {
    let dists = per_distribution(rows, format);
    let total = dists.len();
    let improves = dists.iter().filter(|(_, r)| *r < IMPROVED_RATIO).count();

    // Worst per-distribution regression, as a positive fraction (0.04 = 4% worse).
    let worst_regression = dists
        .iter()
        .map(|(_, r)| (r - 1.0).max(0.0))
        .fold(0.0f64, f64::max);
    // Aggregate gain = mean of the per-distribution relative gains.
    let mean_ratio = dists.iter().map(|(_, r)| *r).sum::<f64>() / total as f64;
    let aggregate_gain = 1.0 - mean_ratio;

    let regressed = worst_regression > REGRESSION_TOLERANCE - 1.0;

    // Order matters, and mirrors the rule table top to bottom: a disqualifying
    // regression outranks a win count, which outranks the magnitude check.
    let (action, reasoning) = if regressed {
        (
            "DO NOT SHIP",
            format!(
                "a distribution regressed by {:.2}% (> 1%)",
                worst_regression * 100.0
            ),
        )
    } else if improves < 3 {
        (
            "DO NOT SHIP",
            format!("improves on {improves} of {total} distributions (< 3)"),
        )
    } else if aggregate_gain < MARGINAL_GAIN {
        (
            "MARGINAL",
            format!(
                "clears the 3-of-4 bar but aggregate gain {:.2}% < 2%",
                aggregate_gain * 100.0
            ),
        )
    } else {
        (
            "SHIP",
            format!(
                "improves {improves}/{total}, worst regression {:.2}%, aggregate gain {:.2}%",
                worst_regression * 100.0,
                aggregate_gain * 100.0
            ),
        )
    };

    Verdict {
        action,
        improves,
        total,
        worst_regression,
        aggregate_gain,
        reasoning,
    }
}

fn print_table(rows: &[Row]) {
    println!();
    println!("Tier 2 quality modes — reconstruction error (rel_l2, lower is better)");
    println!(
        "metric: rel_l2 = sum((w - dequantize(quantize(w)))^2) / sum(w^2), \
         accumulated in f64"
    );
    println!("dequantizers: quant_core::quant_nvfp4::dequantize_nvfp4 / quant_mxfp8::dequantize_mxfp8 (shipped)");
    println!();

    println!(
        "{:<8} {:<13} {:<16} {:>13} {:>13} {:>10} {:>9}",
        "format", "distribution", "shape", "base", "quality", "ratio", "gain"
    );
    println!("{}", "-".repeat(88));
    for r in rows {
        println!(
            "{:<8} {:<13} {:<16} {:>13.6} {:>13.6} {:>10.6} {:>8.2}%",
            r.format.name(),
            r.distribution,
            format!("{} {}", r.shape, r.dims),
            r.base,
            r.quality,
            r.ratio,
            (1.0 - r.ratio) * 100.0
        );
    }
    println!();
    println!(
        "Per-distribution aggregate (mean of the 4 distribution ratios) and worst regression:"
    );
    for format in FORMATS {
        let v = evaluate(rows, format);
        println!(
            "  {:<12} aggregate gain {:>7.2}%   worst regression {:>6.2}%   improved {}/{}",
            format.name(),
            v.aggregate_gain * 100.0,
            v.worst_regression * 100.0,
            v.improves,
            v.total
        );
    }
    println!();

    println!("PRE-REGISTERED DECISION RULE (fixed before any measurement)");
    println!("  improves rel_l2 on >=3 of 4 AND none regresses by >1%  -> SHIP");
    println!("  improves on <3 of 4                                     -> DO NOT SHIP");
    println!("  any distribution regresses by >1%                        -> DO NOT SHIP");
    println!("  gain <2% aggregate                                      -> MARGINAL (keep, do not advertise)");
    println!();
    println!("VERDICT");
    for format in FORMATS {
        let v = evaluate(rows, format);
        println!("  {:<12} {:<12} — {}", format.name(), v.action, v.reasoning);
    }
    println!();
}

// ---------------------------------------------------------------------------
// The computed table, shared between the printout and the timed section
// ---------------------------------------------------------------------------

struct Table {
    cases: Vec<Case>,
    rows: Vec<Row>,
    /// Base results kept for the timed dequantize benchmark, indexed by
    /// (format, case) in the same order the rows were built.
    base_nvfp4: Vec<Nvfp4QuantResult>,
    base_mxfp8: Vec<Mxfp8QuantResult>,
    base_int8: Vec<Int8QuantResult>,
}

fn table() -> &'static Table {
    static TABLE: OnceLock<Table> = OnceLock::new();
    TABLE.get_or_init(|| {
        verify_blob_digest();
        let cases = load_cases();
        let rows = build_rows(&cases);

        // Re-quantize the base arm to keep a live result object for the timed
        // dequantize benchmark below. Cheap relative to the NVFP4 search.
        let mut base_nvfp4 = Vec::new();
        let mut base_mxfp8 = Vec::new();
        let mut base_int8 = Vec::new();
        for c in &cases {
            base_nvfp4.push(quantize_nvfp4_weight(&c.w, c.rows, c.cols));
            base_mxfp8.push(quantize_mxfp8_weight(&c.w, c.rows, c.cols));
            base_int8.push(quantize_int8_weight(
                &c.w,
                c.rows,
                c.cols,
                Int8ScalingMode::Row,
                128,
            ));
        }

        Table {
            cases,
            rows,
            base_nvfp4,
            base_mxfp8,
            base_int8,
        }
    })
}

fn quality_error(c: &mut Criterion) {
    let t = table();
    print_table(&t.rows);

    let mut group = c.benchmark_group("quality_error");
    // Small tensors: the dequantize + rel_l2 pass is microseconds, so keep the
    // sample count modest and the window short.
    group.sample_size(50);
    group.measurement_time(std::time::Duration::from_secs(5));

    for (i, case) in t.cases.iter().enumerate() {
        let elements = case.len() as u64;
        group.throughput(Throughput::Elements(elements));
        let id = case.id.clone();

        group.bench_with_input(BenchmarkId::new("nvfp4", &id), &(), |b, _| {
            b.iter(|| {
                let recon = dequantize_nvfp4(&t.base_nvfp4[i], case.rows, case.cols);
                rel_l2(&case.w, &recon)
            })
        });
        group.bench_with_input(BenchmarkId::new("mxfp8", &id), &(), |b, _| {
            b.iter(|| {
                let recon = dequantize_mxfp8(&t.base_mxfp8[i], case.rows, case.cols);
                rel_l2(&case.w, &recon)
            })
        });
        group.bench_with_input(BenchmarkId::new("int8_clip09", &id), &(), |b, _| {
            b.iter(|| {
                let q = &t.base_int8[i];
                let recon = dequantize_int8(
                    &q.qdata,
                    &q.scale,
                    case.rows,
                    case.cols,
                    Int8ScalingMode::Row,
                    128,
                );
                rel_l2(&case.w, &recon)
            })
        });
    }
    group.finish();
}

criterion_group!(benches, quality_error);
criterion_main!(benches);
